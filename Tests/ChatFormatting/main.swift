import Foundation
let rich = ChatFormatting.render("请在 **星期五** 前完成。\n- 第一项\n- 第二项")
precondition(String(rich.characters) == "请在 星期五 前完成。\n- 第一项\n- 第二项")
precondition(rich.runs.contains { $0.inlinePresentationIntent?.contains(.stronglyEmphasized) == true })
let partial = ChatFormatting.render("还没结束的 **内容")
precondition(String(partial.characters).contains("内容"))
let literal = ChatFormatting.render("代码 `x * y` 不应变成斜体")
precondition(String(literal.characters).contains("x * y"))
precondition(literal.runs.contains { $0.inlinePresentationIntent?.contains(.code) == true })
print("PASS Markdown emphasis, whitespace, code and partial streams")
let blocks = ChatFormatting.blocks("说明：\n```swift\nlet x = 1\nprint(x)\n```\n完成。")
precondition(blocks.count == 3 && !blocks[0].isCode && blocks[1].isCode && blocks[1].language == "swift")
precondition(blocks[1].text == "let x = 1\nprint(x)" && blocks[2].text == "完成。")
let partialCode = ChatFormatting.blocks("正在生成：\n```python\nprint(1)")
precondition(partialCode.count == 2 && partialCode[1].isCode && partialCode[1].text == "print(1)")
let inline = ChatFormatting.blocks("命令 `echo hi` 保持行内。")
precondition(inline.count == 1 && !inline[0].isCode)
print("PASS fenced code blocks and incomplete streaming code")
