import Foundation
var selection = IslandModuleSelection(enabled: [.clipboard, .shelf, .notes, .shelf], selected: .notes)
precondition(selection.enabled == [.clipboard, .shelf, .notes] && selection.selected == .notes)
selection.move(.notes, to: 0)
precondition(selection.enabled == [.notes, .clipboard, .shelf] && selection.selected == .notes)
let restored = IslandModuleSelection.decode(selection.encoded!, fallback: .init(enabled: []))
precondition(restored == selection)
selection.setEnabled(.notes, false)
precondition(selection.selected == .clipboard)
selection.select(.screenshot)
precondition(selection.selected == .clipboard)
selection.setEnabled(.clipboard, false); selection.setEnabled(.shelf, false)
precondition(selection.enabled.isEmpty && selection.selected == nil)
selection.setEnabled(.captions, true)
precondition(selection.selected == .captions)
let fallback = IslandModuleSelection(enabled: [.shelf])
precondition(IslandModuleSelection.decode(Data("invalid".utf8), fallback: fallback) == fallback)
let future = Data(#"{"enabled":["future","notes","notes"],"selected":"future"}"#.utf8)
precondition(IslandModuleSelection.decode(future, fallback: fallback) == .init(enabled: [.notes]))
print("Island module selection, order, restoration and invalid-data handling passed")
