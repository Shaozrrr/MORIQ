import Foundation

let first = UUID()
var labels = CaptionSpeakerNames(sessionID: first)
precondition(labels.displayName(for: nil, session: first) == "未知说话人")
precondition(!labels.setUserName("张三", for: "a", session: first))
precondition(!labels.observe(nil, session: first))
precondition(!labels.observe(" ", session: first))
precondition(labels.observe("a", session: first))
precondition(labels.observe("b", session: first))
precondition(labels.displayName(for: "a", session: first) == "说话人 1")
precondition(labels.displayName(for: "b", session: first) == "说话人 2")
precondition(labels.setUserName(" 小王 ", for: "b", session: first))
precondition(labels.displayName(for: "b", session: first) == "小王")
let segment = UUID()
precondition(!labels.setSpeakerForSegment(segment, id: "unseen", session: first))
precondition(labels.setSpeakerForSegment(segment, id: "b", session: first))
precondition(labels.displayName(forSegment: segment, inferredID: "a", session: first) == "小王")
precondition(labels.setSpeakerForSegment(segment, id: nil, session: first))
precondition(labels.displayName(forSegment: segment, inferredID: "a", session: first) == "未知说话人")
precondition(labels.clearSegmentCorrection(segment, session: first))
precondition(labels.displayName(forSegment: segment, inferredID: "a", session: first) == "说话人 1")
precondition(!labels.setUserName("\n", for: "a", session: first))
precondition(!labels.setUserName("a\nb", for: "a", session: first))
precondition(!labels.setUserName(String(repeating: "a", count: 81), for: "a", session: first))
precondition(labels.setUserName(nil, for: "b", session: first))
precondition(labels.displayName(for: "b", session: first) == "说话人 2")
let next = labels.beginSession()
precondition(!labels.observe("a", session: first))
precondition(!labels.setUserName("小王", for: "b", session: first))
precondition(!labels.setSpeakerForSegment(segment, id: nil, session: first))
precondition(labels.displayName(for: "b", session: next) == "未知说话人")
precondition(labels.observe("b", session: next))
precondition(labels.displayName(for: "b", session: next) == "说话人 1")
precondition(labels.displayName(for: "b", session: first) == "未知说话人")
print("PASS session isolation, explicit naming, reset and unknown speaker")
