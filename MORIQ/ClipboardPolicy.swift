import Foundation

struct ClipboardPolicy {
    func permits(types: [String], sourceBundle: String) -> Bool {
        let excludedTypes: Set<String> = ["org.nspasteboard.concealedtype", "org.nspasteboard.transienttype", "org.nspasteboard.autogeneratedtype"]
        return !types.contains { excludedTypes.contains($0.lowercased()) }
    }
}
